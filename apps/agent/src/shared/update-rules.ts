/**
 * Когда агенту можно обновляться.
 *
 * Обновление ставится перезапуском программы, а программа держит блокировку
 * игрового ПК. Поэтому правила здесь не про версии, а про то, чтобы не выбить
 * из-под гостя оплаченную игру и не тратить сеть зала впустую.
 */

export interface UpdateState {
  /** Идёт оплаченная сессия. */
  playing: boolean;
  /** Машина бездисковая: настройки пришли ключом клуба из общего образа. */
  diskless: boolean;
}

/**
 * Бездисковым машинам обновляться бессмысленно и вредно.
 *
 * Агент лежит внутри образа, а всё записанное поверх исчезает при перезагрузке.
 * Обновление скачается, поставится, пропадёт при ребуте — и скачается снова.
 * На сорока машинах это сорок закачек по восемьдесят мегабайт каждую загрузку
 * зала. Такие машины обновляются правкой образа, и только так.
 */
export function canUpdate(state: UpdateState): boolean {
  if (state.diskless) return false;
  // Перезапуск посреди катки гость воспримет как поломку — и будет прав.
  return !state.playing;
}

/** Почему обновление отложено — строкой в журнал, чтобы не гадать в зале. */
export function skipReason(state: UpdateState): string | null {
  if (state.diskless) return "машина бездисковая: агент обновляется через образ";
  if (state.playing) return "идёт оплаченная сессия";
  return null;
}
