import { describe, expect, it } from "vitest";

import { packageEndingText, switchedText } from "./package-warning.js";

describe("конец пакета", () => {
  it("называет цену поминутки и на сколько хватит баланса", () => {
    expect(packageEndingText(10, 1000, 45)).toBe(
      "Минут пакета осталось: 10. Дальше игра продолжится поминутно по 10 ₸/мин: баланса хватит примерно на 45 мин.",
    );
  });

  it("предупреждает, если денег на поминутку нет", () => {
    expect(packageEndingText(5, 1000, 0)).toContain("пополните счёт");
  });

  it("сообщение о переходе", () => {
    expect(switchedText(1000, 30)).toBe(
      "Пакет закончился — дальше поминутно по 10 ₸/мин. Игра продолжается. Баланса хватит примерно на 30 мин.",
    );
  });
});
