/**
 * Правила опознания машины бездискового зала — чистые функции.
 *
 * MAC приходит от агента в том виде, в каком его отдала операционная система:
 * с двоеточиями или дефисами, в любом регистре. Мы приводим его к одной форме,
 * потому что это ключ, по которому машина находит себя после каждой
 * перезагрузки, — расхождение в разделителе завело бы вторую машину вместо
 * найденной первой.
 */

/** Заведомо не машина зала: виртуальные адаптеры и адрес-заглушка. */
const BLANK = "000000000000";

export function normalizeMac(raw: string): string | null {
  const hex = raw.trim().toLowerCase().replace(/[^0-9a-f]/g, "");
  if (hex.length !== 12) return null;
  if (hex === BLANK) return null;
  return hex.match(/.{2}/g)!.join(":");
}

/**
 * MAC для показа человеку: администратор сверяет его с наклейкой на корпусе
 * или со списком в CCBoot, а там принята запись через дефис в верхнем регистре.
 */
export function formatMac(normalized: string): string {
  return normalized.replace(/:/g, "-").toUpperCase();
}
