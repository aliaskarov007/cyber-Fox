import { describe, expect, it } from "vitest";

import { normalizePhone, parseCsv, parseMoney, pick, splitLine } from "./csv.js";

describe("разбор строки", () => {
  it("делит по запятой", () => {
    expect(splitLine("Айдос,+77010000001,1500", ",")).toEqual(["Айдос", "+77010000001", "1500"]);
  });

  it("не делит внутри кавычек", () => {
    // Имя с запятой — обычное дело в выгрузках.
    expect(splitLine('"Иванов, Иван";+77010000001', ";")).toEqual([
      "Иванов, Иван",
      "+77010000001",
    ]);
  });

  it("удвоенная кавычка внутри значения остаётся одной", () => {
    expect(splitLine('"Клуб ""Арена""";10', ";")).toEqual(['Клуб "Арена"', "10"]);
  });
});

describe("разбор таблицы", () => {
  it("понимает точку с запятой из русской выгрузки", () => {
    const table = parseCsv("Имя;Телефон;Баланс\nАйдос;+77010000001;1500");
    expect(table.headers).toEqual(["имя", "телефон", "баланс"]);
    expect(table.rows[0]["телефон"]).toBe("+77010000001");
  });

  it("срезает BOM от Excel", () => {
    // Без этого первый заголовок не совпадёт ни с одним ожидаемым названием.
    const table = parseCsv("﻿Имя;Телефон\nАйдос;+77010000001");
    expect(table.headers[0]).toBe("имя");
  });

  it("переживает переводы строк Windows и пустой хвост файла", () => {
    const table = parseCsv("Имя;Телефон\r\nАйдос;+77010000001\r\n\r\n");
    expect(table.rows).toHaveLength(1);
  });

  it("недостающие ячейки не ломают строку", () => {
    const table = parseCsv("Имя;Телефон;Баланс\nАйдос;+77010000001");
    expect(table.rows[0]["баланс"]).toBe("");
  });
});

describe("поиск колонки", () => {
  it("берёт первое непустое из возможных названий", () => {
    const row = { имя: "", "полное имя": "Айдос" };
    expect(pick(row, "Имя", "Полное имя")).toBe("Айдос");
  });

  it("отсутствующая колонка даёт пустую строку", () => {
    expect(pick({}, "Имя")).toBe("");
  });
});

describe("деньги", () => {
  it("понимает запятую как разделитель дробной части", () => {
    expect(parseMoney("1500,50")).toBe(150_050);
  });

  it("игнорирует пробелы и знак валюты", () => {
    expect(parseMoney("1 500 ₸")).toBe(150_000);
  });

  it("непонятное значение даёт null, а не ноль", () => {
    // Молчаливый ноль обнулил бы гостю баланс при переезде.
    expect(parseMoney("нет данных")).toBeNull();
    expect(parseMoney("")).toBeNull();
  });

  it("отрицательный баланс переносится как есть: это долг", () => {
    expect(parseMoney("-100")).toBe(-10_000);
  });
});

describe("телефон", () => {
  it("приводит восьмёрку к международному виду", () => {
    expect(normalizePhone("8 701 000 00 01")).toBe("+77010000001");
  });

  it("понимает уже нормальный номер", () => {
    expect(normalizePhone("+7 (701) 000-00-01")).toBe("+77010000001");
  });

  it("слишком короткий номер отбрасывается", () => {
    expect(normalizePhone("12345")).toBeNull();
  });
});
