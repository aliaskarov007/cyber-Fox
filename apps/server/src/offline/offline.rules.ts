/**
 * Проверка отчёта агента о работе без связи — чистая функция.
 *
 * Минуты приходят от агента и ничем не ограничены на входе. Отрицательное и
 * ноль списание отбросит само, но дробное или заведомо невозможное число
 * означает сломанный или подставной отчёт, и до базы его доводить незачем.
 */

/** Больше суток за один отчёт машина отыграть не может. */
export const MAX_OFFLINE_MINUTES = 1440;

/** Годятся только целые минуты в пределах 0..1440. */
export function isAcceptableMinutes(minutes: number): boolean {
  return Number.isInteger(minutes) && minutes >= 0 && minutes <= MAX_OFFLINE_MINUTES;
}
